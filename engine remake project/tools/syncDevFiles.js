#!/usr/bin/env node
// Copies the project's .yaml data files into male/devFiles.js so the
// debug console can read them when the page is opened straight from disk
// (file:// pages can't fetch() local files).
//
//   node tools/syncDevFiles.js            sync once
//   node tools/syncDevFiles.js --watch    sync now, then again every time a
//                                         .yaml in the project root is saved
//
// With --watch running, an open /display todoList panel picks up your
// edits within a couple of seconds - no page reload needed.
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");

function sync() {
    const files = fs.readdirSync(root).filter((f) => /\.ya?ml$/i.test(f)).sort();
    let out = "// AUTO-GENERATED by tools/syncDevFiles.js - do not edit by hand.\n" +
              "// Embedded copies of the project's .yaml files for file:// use.\n" +
              "window.DEV_FILES = window.DEV_FILES || {};\n";
    for (const f of files) {
        const text = fs.readFileSync(path.join(root, f), "utf8").replace(/\r\n/g, "\n");
        out += `window.DEV_FILES[${JSON.stringify(f)}] = ${JSON.stringify(text)};\n`;
    }
    const target = path.join(root, "male", "devFiles.js");
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== out) fs.writeFileSync(target, out);
    console.log(`[${new Date().toLocaleTimeString()}] devFiles.js: embedded ${files.length} file(s): ${files.join(", ")}`);
}

sync();

if (process.argv.includes("--watch")) {
    let timer = null;
    // Watch the folder (not the file): most editors save by replacing the file.
    fs.watch(root, (event, name) => {
        if (!name || !/\.ya?ml$/i.test(name)) return;
        clearTimeout(timer);
        timer = setTimeout(() => { try { sync(); } catch (e) { console.error(e.message); } }, 150);
    });
    console.log("Watching for .yaml changes in", root, "(Ctrl+C to stop)");
}
